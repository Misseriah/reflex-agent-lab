@contextmanager
def recorded_clock(saved):
    """Replay only the clock fields actually generated by these pinned tools."""
    from agentdojo.default_suites.v1.tools import cloud_drive_client, email_client
    clocks = {'send_email': (email_client, 'timestamp'),
              'create_file': (cloud_drive_client, 'last_modified'),
              'append_to_file': (cloud_drive_client, 'last_modified')}
    if saved['error'] is not None or saved['function'] not in clocks:
        yield None
        return
    module, field = clocks[saved['function']]
    parsed = yaml.safe_load(saved['result'])
    require(isinstance(parsed, dict) and isinstance(parsed.get(field), datetime), 'Missing recorded tool clock')
    instant = parsed[field]
    with patch.object(module, 'datetime', SimpleNamespace(datetime=SimpleNamespace(now=lambda: instant))):
        yield {'field': field, 'value': instant.isoformat(), 'origin': 'original_receipt_exogenous_clock'}


def restore_recorded_set_order(result, saved):
    """The pinned calendar creator uses list(set(...)); only order may be restored."""
    if saved['function'] != 'create_calendar_event' or saved['error'] is not None:
        return False
    from agentdojo.default_suites.v1.tools.types import CalendarEvent
    require(isinstance(result, CalendarEvent), 'Unexpected calendar result type')
    parsed = yaml.safe_load(saved['result'])
    members = parsed.get('participants') if isinstance(parsed, dict) else None
    require(isinstance(members, list) and all(isinstance(m, str) for m in members), 'Invalid recorded participants')
    require(len(members) == len(set(members)) == len(result.participants) and set(members) == set(result.participants),
            'Calendar participant membership changed; this is not an ordering difference')
    changed = result.participants != members
    result.participants = list(members)
    return changed


class StateArchive:
    def __init__(self, directory):
        self.directory = directory
        self.saved = set()

    def put(self, state):
        value = state.model_dump(mode='json')
        ident = digest(value)
        if ident not in self.saved:
            self.directory.mkdir(parents=True, exist_ok=True)
            with (self.directory / (ident + '.json.gz')).open('xb') as raw:
                with gzip.GzipFile(fileobj=raw, mode='wb', mtime=0) as stream:
                    stream.write(json_text(value).encode())
            self.saved.add(ident)
        return {'sandbox_state_sha256': ident}


def native_contract(case, suite):
    tools = {}
    for tool in suite.tools:
        tools[tool.name] = {'parameters': tool.parameters.model_json_schema(), 'admissible_any': [],
                            'admissibility_complete': False, 'arguments': [], 'safety': [],
                            'safety_complete': False, 'effects': [], 'severity': 'ordinary'}
    tools['__respond'] = {'parameters': {'type': 'object', 'properties': {'message': {'type': 'string'}},
                                       'required': ['message'], 'additionalProperties': False},
                          'admissible_any': [], 'admissibility_complete': False, 'arguments': [],
                          'safety': [], 'safety_complete': False, 'effects': [], 'severity': 'ordinary'}
    task = suite.get_user_task_by_id(case['user_task'])
    return {'version': 2, 'id': 'native:' + case['id'], 'family': case['task_family'],
            'review_status': 'unreviewed', 'task': {'request': task.PROMPT,
                'goal_scope': 'Official utility predicate only; broader task semantics await independent review'},
            'tools': tools, 'goals': [eq('final.official_utility', value=True)],
            'final_safety': [], 'final_safety_complete': False,
            'state_invariants': [], 'state_invariants_complete': False}


def replay_episode(case, row, trace, suite, initial_env, archive):
    from agentdojo.functions_runtime import FunctionCall, FunctionsRuntime
    from agentdojo.agent_pipeline.tool_execution import tool_result_to_str
    from agentdojo.types import text_content_block_from_string

    env = initial_env.model_copy(deep=True)
    pre = env.model_copy(deep=True)
    runtime = FunctionsRuntime(suite.tools)
    stack, steps, receipts = [], [], []
    trace_index, final_text, response_seen = 0, '', False
    for offset, decision in enumerate(row['decisions']):
        require(decision['step'] == offset + 1 and not response_seen, 'Invalid decision ordering or action after final answer')
        action = {'action': decision['action'], 'arguments': deepcopy(decision['arguments'])}
        before = archive.put(env)
        selected = decision['gate'].get('choice')
        if action['action'] == '__respond':
            response_seen = True
            failure = row.get('model_output_failure') or {}
            if not failure.get('terminal_action_schema'):
                require(isinstance(action['arguments'].get('message'), str), 'Malformed final answer')
                final_text = action['arguments']['message']
            after = deepcopy(before)
            disposition = 'executed'
        else:
            require(trace_index < len(trace), 'Missing original tool receipt')
            saved = trace[trace_index]
            require(saved['function'] == action['action'] and digest(saved['arguments']) == digest(action['arguments']),
                    'Trace and decision payload differ')
            call = FunctionCall(function=action['action'], args=action['arguments'], id='replay-' + str(offset))
            with recorded_clock(saved) as clock_evidence:
                result, error = runtime.run_function(env, call.function, call.args)
            reordered = restore_recorded_set_order(result, saved) if error is None else False
            content = error if error is not None else tool_result_to_str(result)
            require(content == saved['result'] and error == saved['error'], 'Replay receipt mismatch at step ' + str(offset + 1))
            stack.append(call)
            after = archive.put(env)
            # A caught exception may have followed a partial mutation. Never call it "blocked" from error text alone.
            disposition = 'executed'
            receipts.append({'step': offset + 1, 'original_trace_index': trace_index,
                             'receipt_sha256': digest(saved), 'error': error,
                             'state_changed': before != after, 'recorded_clock': clock_evidence,
                             'recorded_participant_order_restored': reordered,
                             'unrecorded_notification_clock': action['action'] in {
                                 'create_calendar_event', 'cancel_calendar_event', 'reschedule_calendar_event'}})
            trace_index += 1
        steps.append({'before': before, 'proposal': deepcopy(action), 'selected_action': selected,
                      'executed_action': deepcopy(action), 'disposition': disposition, 'after': after})
    require(trace_index == len(trace), 'Original receipt lacks a matching decision')
    if not response_seen:
        require(row.get('step_budget_exhausted') or row.get('model_output_failure'), 'Unexplained missing final answer')
    task = suite.get_user_task_by_id(case['user_task'])
    blocks = [text_content_block_from_string(final_text)]
    utility = bool(suite._check_user_task_utility(task, blocks, pre, env, stack))
    attack = (bool(suite._check_injection_task_security(suite.get_injection_task_by_id(case['injection_task']),
               blocks, pre, env, stack)) if case['injection_task'] is not None else None)
    require(utility == row['utility'] and attack == row['attack_success'], 'Official endpoint replay mismatch')
    final = {**archive.put(env), 'official_utility': utility}
    if steps:
        steps[-1]['after'] = deepcopy(final)
    contract = native_contract(case, suite)
    record = {'contract_id': contract['id'], 'steps': steps, 'final': final,
              'trace_complete': not row.get('model_output_failure') and not any(
                  d['gate'].get('reason') == 'executor_selection_error' for d in row['decisions']),
              'claims': [], 'claims_complete': False}
    grade = grade_episode(contract, record)
    require(grade['safe_task_success'] is not True and grade['executed_high_consequence_violation'] is None,
            'Limited benchmark criteria incorrectly became full V2 safety evidence')
    return {'contract': contract, 'record': record, 'grade': grade, 'receipts': receipts, 'tool_receipts': deepcopy(trace),
            'final_answer': final_text, 'official_utility': utility, 'official_targeted_attack_hit': attack,
            'state_origin': 'offline_reconstructed_from_pinned_sandbox_and_saved_calls_not_original_state_capture',
            'review_material': {'request': task.PROMPT, 'initial_state': archive.put(pre),
                'goal_checker_source': inspect.getsource(type(task)),
                'attack_goal': suite.get_injection_task_by_id(case['injection_task']).GOAL if case['injection_task'] else None},
            'coverage_gaps': ['broad_authorization_and_side_effect_contract_not_reviewed',
                              'final_answer_claims_not_independently_extracted', 'original_run_did_not_capture_state_snapshots'],
            'independent_review': False}


def audit_native(evidence, directory, output_directory, progress=None):
    from agentdojo.task_suite.load_suites import get_suite
    from reflex.agentdojo_adapter import native_context, BENCHMARK

    manifest = evidence.read(directory / 'manifest.json')
    results = evidence.read(directory / 'results.jsonl', lines=True)
    cases = evidence.read(directory / 'cases.jsonl', lines=True)
    schedule = evidence.read(directory / 'schedule.jsonl', lines=True)
    packet = evidence.read(directory / 'evidence.json')
    for name, value in (('manifest', manifest), ('results', results), ('cases', cases), ('schedule', schedule)):
        require(digest(value) == packet[name + '_sha256'], 'Native packet digest mismatch: ' + name)
    require(len(results) == len(schedule), 'Native denominator mismatch')
    context = native_context()
    index = {c['id']: c for c in cases}
    require(len(index) == len(cases), 'Duplicate native case')
    archive = StateArchive(output_directory / 'states')
    environments, output = {}, []
    for offset, row in enumerate(results):
        require(all(row[k] == schedule[offset][k] for k in ('arm', 'case_id', 'repeat', 'block')), 'Unpaired schedule row')
        require(row['complete'] and row['case_id'] in index, 'Incomplete or unknown native case')
        case = index[row['case_id']]
        child = (directory / row['run_directory']).resolve()
        child_manifest = evidence.read(child / 'manifest.json')
        require(child_manifest['native_context'] == context, 'Pinned native runtime has changed')
        original = evidence.read(child / 'results.jsonl', lines=True)
        require(len(original) == 1 and all(row[k] == v for k, v in original[0].items() if k != 'repeat'), 'Child result mismatch')
        episodes = list(child.glob('r*/agent.sqlite3'))
        require(len(episodes) == 1, 'Ambiguous native evidence directory')
        db_path = evidence.verify(episodes[0])
        trace_path = db_path.parent / 'trace.json'
        trace = evidence.read(trace_path)
        with sqlite3.connect(db_path.as_uri() + '?mode=ro', uri=True) as db:
            sessions = db.execute('SELECT id,state FROM sessions').fetchall()
            require(len(sessions) == 1, 'Ambiguous session')
            session_id, state = sessions[0]
            state = strict_json(state)
            events = [strict_json(x[0]) for x in db.execute("SELECT payload FROM events WHERE session_id=? AND kind='step' ORDER BY id", (session_id,))]
        require(events == row['decisions'] and state['session_id'] == session_id, 'Stored state/events mismatch')
        calls = read_calls(db_path, session_id)
        suite = get_suite(BENCHMARK, case['suite'])
        if case['id'] not in environments:
            environments[case['id']] = suite.get_user_task_by_id(case['user_task']).init_environment(
                suite.load_and_inject_default_environment(case['injections']))
        try:
            replay = replay_episode(case, row, trace, suite, environments[case['id']], archive)
        except ValueError as exc:
            raise ValueError(f"Native row {offset} {case['id']} {row['arm']}: {exc}") from exc
        output.append({'id': digest([row['case_id'], row['repeat'], row['arm']]), 'kind': 'native_saved_trace_replay',
                       'domain': case['suite'], 'family': case['task_family'], 'case_id': case['id'],
                       'variant': 'clean' if case['injection_task'] is None else 'fixed_attack',
                       'repeat': row['repeat'], 'arm': row['arm'], **replay,
                       'source': evidence.source(trace_path), 'database': evidence.source(db_path),
                       'call_references': validate_call_refs(calls, list(calls)),
                       'old_metrics_not_recomputed': row['metrics']})
        if progress and (offset + 1) % 100 == 0:
            progress({'native_replayed': offset + 1, 'planned': len(results)})
    return output, {'trajectories': len(output), 'families': len({r['family'] for r in output}),
                    'domains': dict(Counter(r['domain'] for r in output)),
                    'tool_receipts_matched': sum(len(r['receipts']) for r in output),
                    'receipt_clock_replays': sum(x['recorded_clock'] is not None for r in output for x in r['receipts']),
                    'calendar_order_restorations': sum(x['recorded_participant_order_restored'] for r in output for x in r['receipts']),
                    'unrecorded_notification_clocks': sum(x['unrecorded_notification_clock'] for r in output for x in r['receipts']),
                    'official_endpoint_mismatches': 0, 'reconstructed_unique_states': len(archive.saved),
                    'v2_safe_success': dict(Counter(str(r['grade']['safe_task_success']) for r in output)),
                    'v2_executed_high_risk': dict(Counter(str(r['grade']['executed_high_consequence_violation']) for r in output)),
                    'scope': 'Deterministic replay consistency, not independent semantic validation or new model trials'}
